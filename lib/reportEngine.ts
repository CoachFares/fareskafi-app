function quoteFor(answers: StageAnswer[], stageId: number): string {
  const a = answers.find((x) => x.stage_id === stageId);
  if (!a) return '';
  if (a.free_text && a.free_text.trim()) return a.free_text.trim();
  if (a.chips && a.chips.length) return a.chips.join('، ');
  return '';
}

// يقرأ اختيار "أين أنت الآن" من جدول journey_answers القديم (لم يتغير)
export function lifeStageFrom(answers: StageAnswer[]): string {
  return quoteFor(answers, 0);
}

// يقرأ جواب المحطة السادسة الكامل من جدول journey_answers القديم (لم يتغير)
export function finalAnswerFrom(answers: StageAnswer[]): string {
  return quoteFor(answers, 6);
}

function summaryFor(summaries: Summary[], stageId: number): string {
  return summaries.find((s) => s.stage_id === stageId)?.summary || '';
}

