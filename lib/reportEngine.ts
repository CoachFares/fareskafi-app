// توجيه دقيق حسب اختيار "أين أنت الآن" — لا يكفي تمرير الجملة وحدها، لأنها تترك للنموذج افتراضات قد تكون خاطئة
function lifeStageGuidance(lifeStage: string): string {
  if (!lifeStage) return '';
  if (lifeStage.includes('لست في علاقة')) {
    return 'مهم جدا: هذا الشخص ليس في علاقة حالية، ويريد فهم نمطه العام في العلاقات. لا تفترض وجود ألم أو علاقة نشطة الآن، ولا تسأل عن "علاقتك الحالية". وجه الأسئلة نحو تجاربه أو علاقاته السابقة إن وجدت، أو نحو ميوله ومخاوفه المتوقعة تجاه العلاقات بشكل عام.';
  }
  if (lifeStage.includes('انفصال')) {
    return 'هذا الشخص يمر بانفصال مؤلم حديث. تعامل معه باحتواء أكبر من المعتاد، ولا تستعجله نحو "الحل" أو "الخطوة القادمة" قبل أن يعبر عن الألم نفسه بما يكفي.';
  }
  if (lifeStage.includes('حيرة')) {
    return 'هذا الشخص في علاقة قائمة حاليا لكنه في حيرة بشأنها. ساعده يصل لوضوح أعمق حول نفسه، دون أن تفترض له قرارا مسبقا (بقاء أو انفصال) ودون أن تسأل عنه مباشرة.';
  }
  if (lifeStage.includes('بداية علاقة جديدة')) {
    return 'هذا الشخص في بداية علاقة جديدة. وجه الأسئلة نحو أنماطه من علاقات أو تجارب سابقة قد تتكرر هنا، لا نحو أزمة أو ألم حالي في هذه العلاقة الجديدة.';
  }
  return '';
}

