function quoteFor(answers: StageAnswer[], stageId: number): string {
  const a = answers.find((x) => x.stage_id === stageId);
  if (!a) return '';
  if (a.free_text && a.free_text.trim()) return a.free_text.trim();
  if (a.chips && a.chips.length) return a.chips.join('، ');
  return '';
}

// يبني نص التقرير الأساسي (بدون ذكاء اصطناعي) — دالة نقية، سهلة الاختبار
export function buildReport(answers: StageAnswer[]) {
  const q = (id: number) => quoteFor(answers, id) || 'لم تتم الإجابة على هذا الجزء بعد.';
  const pain = q(1), need = q(2), cost = q(3), roots = q(4), choice = q(5);
  const finalAnswer = quoteFor(answers, 6);

  const closing = `رأينا معًا: الوجع الحقيقي كان — ${quoteFor(answers, 1) || 'شعورًا لم يُسمَّ بعد'}. خلفه، كانت حاجة لم تُقال: ${quoteFor(answers, 2) || 'حاجة ما زالت تبحث عن كلماتها'}. وعشان تحميها، دفعت من نفسك ثمنًا: ${quoteFor(answers, 3) || 'جزءًا لم تلاحظه بعد'}. اليوم، تعرف من أين بدأ هذا، واخترت بوعي: ${quoteFor(answers, 5) || 'أن تبدأ برؤية نمطك بصدق'}. هذه ليست نهاية القصة — هذه أول مرة تراها بوضوح.`;

  return {
    sections: [
      { key: 'الوجع الذي ظهر', text: pain },
      { key: 'الحاجة التي كانت خلفه', text: need },
      { key: 'الطريقة التي حاولت تحمي نفسك فيها', text: cost },
      { key: 'من أين بدأ هذا', text: roots },
      { key: 'اختيارك الجديد', text: choice },
    ],
    closingMessage: closing,
    finalAnswer,
  };
}

// يبني الـ prompt المرسل لنموذج الذكاء الاصطناعي عند طلب "تحليل أعمق"
