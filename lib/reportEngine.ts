// السؤال الأول لمحطة من المحطات ١ إلى ٥، مبني على ملخصات المحطات السابقة لها فقط
export function buildStationOpenPrompt(stageId: number, priorSummaries: Summary[], lifeStage: string) {
  const stage = STAGES.find((s) => s.id === stageId)!;
  const context = STAGES.filter((s) => s.id < stageId).map((s) => {
    const summary = summaryFor(priorSummaries, s.id);
    return summary ? { محطة: s.title, ملخص: summary } : null;
  }).filter(Boolean);

  return `${STYLE_PREFIX}

${lifeStage ? `الشخص وصف وضعه الحالي بأنه: "${lifeStage}".` : ''}

أنت تفتح المحطة رقم ${stageId} من رحلة تأملية عنوانها "${stage.title}"، وغرضها: ${stage.directive}.

${context.length ? `ملخص ما دار في المحطات السابقة:\n${JSON.stringify(context, null, 2)}` : 'هذه أول محطة في رحلته.'}

اكتب سؤالا تأمليا واحدا أصيلا يفتح به هذه المحطة، يخدم غرضها مباشرة. إن وجدت خيطا حقيقيا من المحطات السابقة يستحق الإشارة إليه، اربط السؤال به بلطف. لا تكرر صياغات جاهزة أو مألوفة في هذا المجال.

أعد ردك بصيغة JSON فقط: {"question": "السؤال نفسه، جملة أو جملتين كحد أقصى"}`;
}

// بعد كل إجابة داخل المحطة، يقرر: سؤال متابعة يحفر في جانب ناقص، أو ملخص ينهي المحطة
export function buildStationTurnPrompt(stageId: number, exchanges: Exchange[], priorSummaries: Summary[], lifeStage: string) {
  const stage = STAGES.find((s) => s.id === stageId)!;
  const remaining = STATION_CAP - exchanges.length;

  return `${STYLE_PREFIX}

${lifeStage ? `الشخص وصف وضعه الحالي بأنه: "${lifeStage}".` : ''}

أنت في محطة عنوانها "${stage.title}"، وغرضها: ${stage.directive}.

المحادثة داخل هذه المحطة حتى الآن:
${JSON.stringify(exchanges, null, 2)}

باقي لك ${remaining} سؤال كحد أقصى قبل أن تضطر لإنهاء هذه المحطة.

قاعدة صارمة: أي إجابة سطحية أو بلا معنى حقيقي — سواء كانت "لا أعرف"، أو جملة عامة عائمة تصلح لأي شخص، أو كلمة أو كلمتين بلا تفصيل ملموس، أو تكرارا لما قيل سابقا بصياغة مختلفة — تعتبر دائما غير كافية وتستحق سؤال متابعة يدفعه لتفصيل ملموس حقيقي، إلا إذا وصلت فعلا للحد الأقصى من الأسئلة (${remaining} = 0). لا تكتف بأن الشخص "رد بشيء"، تأكد أن ما قاله فعلا يحمل معنى محددا يخصه هو، لا عبارة عامة قد يقولها أي أحد.

إن وصلت للحد الأقصى ولم تحصل على إجابة ذات معنى، لا تكتب في الملخص أنه "لا يعرف" أو تختلق تفصيلا لم يقله، بل صف بصدق أنه تجنب الإجابة المباشرة أو التعمق، فهذا بحد ذاته ملاحظة ذات قيمة.

قرر بصدق: هل تغطى غرض هذه المحطة بشكل كاف عبر ما قاله الشخص فعلا لا مجرد كونه رد بأي شيء، أم ينقصه جانب حقيقي يستحق سؤالا إضافيا؟ لا تسأل من أجل السؤال، ولا تكرر ما سبق طرحه أو الإجابة عنه.

- إن نقص جانب حقيقي ومهم، ولم تنته الأسئلة المتاحة: أعد {"done": false, "reflection": "جملة قصيرة واحدة تعكس فيها ما قاله في إجابته الأخيرة تحديدا، تثبت أنك سمعته بصدق", "question": "سؤال المتابعة، يحفر في الجانب الناقص تحديدا"}
- إن تغطى الغرض بشكل كاف، أو انتهت الأسئلة المتاحة (${remaining} = 0): أعد {"done": true, "summary": "ملخص من ثلاث إلى خمس جمل، يدمج كل ما قاله في هذه المحطة بصياغة متماسكة، قريبة من كلماته هو قدر الإمكان"}

أعد ردك بصيغة JSON فقط بأحد الشكلين أعلاه، بدون أي نص خارجها.`;
}

