function quoteFor(answers: StageAnswer[], stageId: number): string {
  const a = answers.find((x) => x.stage_id === stageId);
  if (!a) return '';
  if (a.free_text && a.free_text.trim()) return a.free_text.trim();
  if (a.chips && a.chips.length) return a.chips.join('، ');
  return '';
}

// يبني نص التقرير الأساسي، بلا ذكاء اصطناعي، دالة نقية سهلة الاختبار
export function buildReport(answers: StageAnswer[]) {
  const q = (id: number) => quoteFor(answers, id) || 'لم تصل الإجابة عن هذا الجزء بعد';
  const pain = q(1), need = q(2), cost = q(3), roots = q(4), choice = q(5);
  const finalAnswer = quoteFor(answers, 6);

  const closing = `تكشف رحلتك عن وجع أساسه: ${quoteFor(answers, 1) || 'شعور لم يجد اسما بعد'}. وخلف هذا الوجع، كانت تختبئ حاجة صامتة: ${quoteFor(answers, 2) || 'حاجة ما زالت تبحث عن كلماتها'}. ولحماية هذه الحاجة، دفعت من ذاتك ثمنا: ${quoteFor(answers, 3) || 'جزءا منك لم تلحظه بعد'}. اليوم، بعد أن رأيت من أين بدأ هذا كله، اخترت بوعي أن: ${quoteFor(answers, 5) || 'تبدأ برؤية نمطك بصدق'}. هذه ليست نهاية القصة، بل أول مرة تراها فيها بهذا الوضوح.`;

  return {
    sections: [
      { key: 'الوجع الذي كشفته الرحلة', text: pain },
      { key: 'الحاجة الصامتة خلف الوجع', text: need },
      { key: 'الثمن الذي دفعته لتبقى محبوبا', text: cost },
      { key: 'نقطة البداية', text: roots },
      { key: 'خطوتك الجديدة', text: choice },
    ],
    closingMessage: closing,
    finalAnswer,
  };
}

// يبني الطلب المرسل للذكاء الاصطناعي لتوليد سؤال محطة واحدة حيا، مبنيا على ما سبقه فعليا
export function buildNextQuestionPrompt(stageId: number, answers: StageAnswer[]) {
  const stage = STAGES.find((s) => s.id === stageId)!;
  const lifeStage = quoteFor(answers, 0);
  const priorQA = STAGES.filter((s) => s.id < stageId).map((s) => {
    const a = answers.find((x) => x.stage_id === s.id);
    const question = a?.question_text || s.fallbackQ;
    const answer = quoteFor(answers, s.id);
    return answer ? { محطة: s.title, السؤال_الذي_طرح: question, الإجابة: answer } : null;
  }).filter(Boolean);

  return `أنت تكتب نيابة عن مختص علاقات يدعى "فارس كافي"، بأسلوب مباشر، صريح، وصادق، لكنه إنساني ولطيف في الوقت نفسه. اكتب بالعربية الفصحى الحديثة حصرا، من دون أي تشكيل إلا في الكلمات التي يتغير معناها من دونه.

${lifeStage ? `الشخص وصف وضعه الحالي بأنه: "${lifeStage}".` : ''}

أنت الآن في المحطة رقم ${stageId} من رحلة تأملية عنوانها "${stage.title}"، وغرضها: ${stage.directive}.

${priorQA.length ? `فيما يلي ما شاركه الشخص فعلا في المحطات السابقة:\n${JSON.stringify(priorQA, null, 2)}` : 'هذه أول محطة في رحلته، لا توجد إجابات سابقة بعد.'}

اكتب سؤالا تأمليا واحدا أصيلا لهذه المحطة تحديدا. إن وجدت خيطا حقيقيا يربط بما قاله سابقا، ابن السؤال عليه مباشرة بإشارة لطيفة إلى ما قاله؛ إن لم يوجد خيط واضح، اكتب سؤالا أصيلا يخدم غرض المحطة دون تكلف. لا تكرر صياغات الأسئلة الجاهزة أو المألوفة في هذا المجال. تجنب أي تشخيص أو حكم.

أعد ردك بصيغة JSON فقط، بدون أي نص خارجها، بالشكل التالي بالضبط:
{"narrative": "جملة تمهيدية واحدة قصيرة جدا، أقل من اثنتي عشرة كلمة", "question": "السؤال نفسه، جملة أو جملتين كحد أقصى"}`;
}

// يبني النص المرسل إلى نموذج الذكاء الاصطناعي عند توليد التحليل الشخصي النهائي
export function buildAiPrompt(answers: StageAnswer[]) {
  const payload = STAGES.map((s) => {
    const a = answers.find((x) => x.stage_id === s.id);
    return { stage: s.title, question_asked: a?.question_text || s.fallbackQ, answer: quoteFor(answers, s.id) || null };
  });
  const lifeStage = quoteFor(answers, 0);

  return `أنت تكتب نيابة عن مختص علاقات يدعى "فارس كافي"، بأسلوب مباشر، صريح، وصادق، لكنه إنساني ولطيف في الوقت نفسه. اكتب بالعربية الفصحى الحديثة حصرا، من دون أي تشكيل إلا في الكلمات التي يتغير معناها من دونه. تجنب العبارات الإنشائية الجاهزة والنصائح العامة، واكتب كأنك تخاطب هذا الشخص تحديدا لا شخصا عاما.

${lifeStage ? `الشخص وصف وضعه الحالي بأنه: "${lifeStage}". اجعل نبرة التحليل تراعي هذا السياق تحديدا (شخص يتعافى من انفصال يحتاج احتواء أكثر، شخص في حيرة يحتاج وضوحا، شخص مقبل على بداية جديدة يحتاج تنبيها لطيفا).` : ''}

فيما يلي رحلة هذا الشخص عبر ست محطات (الوجع، الحاجة، الثمن، نقطة البداية، الاختيار، الجواب)، بصيغة JSON:

${JSON.stringify(payload, null, 2)}

مهمتك: اقرأ الإجابات الست معا، لا كل إجابة منفردة، وابحث عن أصدق ملاحظة تربط بينها. قد تكون هذه الملاحظة واحدة من أربعة أنواع:
١. تناقض حقيقي بين محطتين (مثلا: يصف نفسه بأنه يطلب احتياجاته، بينما يصف في محطة أخرى أنه اعتاد السكوت عنها).
٢. ثبات لافت، إن كانت كل الإجابات متسقة بشكل واضح؛ في هذه الحالة السؤال الحقيقي ليس "لماذا لا يرى نمطه" بل "لماذا يراه ولا يتحرك".
٣. غياب لافت، كأن يصف الطرف الآخر باستمرار ولا يذكر فعله هو، أو تأتي إجابة الاختيار الجديد أقصر وأعم من باقي إجاباته.
٤. تحول ملحوظ بين نبرة المحطات الأولى ونبرة المحطات الأخيرة، من لغة المتلقي السلبي إلى لغة صاحب القرار، أو العكس.

لا تختلق تناقضا إن لم يكن موجودا فعلا. اختر الملاحظة الأصدق فقط، وابن عليها. اكتب فقرة تحليل واحدة، من خمس إلى سبع جمل، ثم اربطها بخطوة عملية واحدة نابعة من هذه الملاحظة تحديدا لا نصيحة عامة منفصلة عنها. اختم بسؤال واحد مفتوح يستحق أن يجلس معه هذا الشخص وحده.`;
}
